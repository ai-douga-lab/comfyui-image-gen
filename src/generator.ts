function wireAbort(ctl: GeneratorController, stream: { controller: AbortController }) {
  ctl.onAborted(() => {
    console.info("Generation aborted by user.");
    stream.controller.abort();
  });
}

/**
 * Stream the completion into LM Studio. Tool calls are buffered until their arguments are complete,
 * so that `beforeToolCall` can print a line of text (e.g. which images go into the generation)
 * before LM Studio starts the tool call.
 */
async function consumeStream(
  stream: AsyncIterable<any>,
  ctl: GeneratorController,
  beforeToolCall: (name: string, args: any) => string | undefined,
) {
  let current: ToolCallState | null = null;
  let textSoFar = "";

  function maybeFlushCurrentToolCall() {
    if (current === null || current.name === null) {
      return;
    }
    let args: any = {};
    try {
      args = JSON.parse(current.arguments || "{}");
    } catch (e) {
      console.error("Tool call arguments are not valid JSON:", current.arguments);
    }
    const text = beforeToolCall(current.name, args);
    if (text) ctl.fragmentGenerated(textSoFar.trim() && !textSoFar.endsWith("\n\n") ? `\n\n${text}` : text);
    ctl.toolCallGenerationStarted();
    ctl.toolCallGenerationNameReceived(current.name);
    if (current.arguments) ctl.toolCallGenerationArgumentFragmentGenerated(current.arguments);
    ctl.toolCallGenerationEnded({ type: "function", name: current.name, arguments: args, id: current.id });
    current = null;
  }

  for await (const chunk of stream) {
    const delta = chunk.choices?.[0]?.delta as
      | {
          content?: string;
          tool_calls?: Array<{
            index: number;
            id?: string;
            function?: { name?: string; arguments?: string };
          }>;
        }
      | undefined;

    /* Text streaming */
    if (delta?.content) {
      textSoFar += delta.content;
      ctl.fragmentGenerated(delta.content);
    }

    /* Tool calls: collect now, hand to LM Studio once complete (see maybeFlushCurrentToolCall) */
    for (const toolCall of delta?.tool_calls ?? []) {
      if (toolCall.id !== undefined) {
        maybeFlushCurrentToolCall();
        current = { id: toolCall.id, name: null, index: toolCall.index, arguments: "" };
      }
      if (toolCall.function?.name && current) current.name = toolCall.function.name;
      if (toolCall.function?.arguments && current) current.arguments += toolCall.function.arguments;
    }

    if (chunk.choices?.[0]?.finish_reason) {
      maybeFlushCurrentToolCall();
    }
  }
  maybeFlushCurrentToolCall();

  console.info("Generation completed.");
}

/** 「[a1][a2]を入力して[v1] (バナナの画像)を生成しました。」 */
function generatedMessage(labels: string[], media: MediaState): string {
  return labels
    .map(l => {
      const info = media.info[l];
      const refs = info?.refs?.length ? `${tags(info.refs)}を入力して` : "";
      const title = info?.title ? ` (${info.title})` : ""; // space: "[v1](...)" would render as a link
      return `${refs}[${l}]${title}を生成しました。`;
    })
    .join("\n\n");
}

/* -------------------------------------------------------------------------- */
/*                                     API                                    */
/* -------------------------------------------------------------------------- */

export async function generate(ctl: GeneratorController, history: Chat) {
  const config = ctl.getPluginConfig(configSchematics);
  const model = config.get("model");
  const globalConfig = ctl.getGlobalPluginConfig(globalConfigSchematics);

  /* 1. Setup client & payload */
  const dir = mediaDir(ctl);
  const media = await loadMedia(dir);
  const openai = createOpenAI(globalConfig);
  // Shrink images sent to the model (the originals still go to ComfyUI).
  setVisionOptions({
    maxMegapixels: globalConfig.get("visionMegapixels"),
    cacheDir: join(dir, ".vision_cache"),
  });
  const messages = await toOpenAIMessages(ctl, history, media);
  await saveMedia(dir, media);
  const tools = toOpenAITools(ctl);

  /* 2. Show freshly generated images in the chat (the plugin does this, not the model) */
  const generated = justGenerated(history).filter(label => media.variants[label]);
  for (const label of generated) {
    ctl.fragmentGenerated(`![${label}](./${basename(media.variants[label])})\n\n`);
  }

  // Fast mode: do not ask the model to comment on the new image(s); end the turn right away.
  // The images are still shown to the model in later turns, so it can refer to [v1], [v2], ...
  if (generated.length && !globalConfig.get("reviewGenerated")) {
    ctl.fragmentGenerated(generatedMessage(generated, media));
    return;
  }

  /* 3. Kick off streaming completion */
  const stream = await openai.chat.completions.create({
    model: model,
    messages,
    tools,
    stream: true,
  });

  /* 4. Before generate_image runs:
   *    「[a3][a4]として画像をアップロードしました。[a1]…[a4]を入力して、画像の生成を開始します。」 */
  const all = [...history];
  let uploaded = all[all.length - 1]?.getRole() === "user" ? media.turnAttachments : [];
  const beforeToolCall = (name: string, args: any) => {
    if (name !== "generate_image") return undefined;
    const { labels } = resolveRefs(String(args?.prompt ?? ""), media, globalConfig.get("autoAttachRefs"));
    const refs = labels.filter(l => media.attachments[l] ?? media.variants[l]);
    let text = uploaded.length ? `${tags(uploaded)}として画像をアップロードしました。` : "";
    uploaded = []; // only once per turn
    text += refs.length ? `${tags(refs)}を入力して、画像の生成を開始します。` : "画像の生成を開始します。";
    return `${text}\n\n`;
  };

  /* 5. Abort wiring & stream processing */
  wireAbort(ctl, stream as any);
  await consumeStream(stream as any, ctl, beforeToolCall);
}
