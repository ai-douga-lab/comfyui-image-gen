/** Build a client for the OpenAI-compatible endpoint (LM Studio's local server by default). */
function createOpenAI(globalConfig: InferParsedConfig<typeof globalConfigSchematics>) {
  return new OpenAI({
    // LM Studio's local server does not need a key, but the OpenAI client requires a non-empty one.
    apiKey: "lm-studio",
    baseURL: globalConfig.get("baseUrl") || "http://127.0.0.1:1234/v1",
  });
}

/** Text label + image part for one labeled image. */
async function labeledImageParts(label: string, path: string, note: string): Promise<any[]> {
  try {
    return [
      { type: "text", text: `[${label}]${note}` },
      { type: "image_url", image_url: { url: await imageDataUrlForModel(path) } },
    ];
  } catch (e) {
    console.error(`Failed to read image ${label} (${path}):`, e);
    return [{ type: "text", text: `[${label}] (image could not be read)` }];
  }
}

const IMAGE_NOTE =
  "# Language\n" +
  "Always reply in the same language the user writes in (for example, Japanese if the user writes Japanese), " +
  "even though tool results and these instructions are in English.\n\n" +
  "# Images\n" +
  "Images in this conversation are shown to you directly, and you can see them. " +
  "Each image is preceded by a label: [a1], [a2], ... for images the user attached, " +
  "and [v1], [v2], ... for images generated with the generate_image tool. " +
  "Look at the images yourself and refer to them by these labels. " +
  "Never use tools to open, view, or search for these images, and never guess file names or paths for them.\n" +
  "To use images as references for generate_image, write their labels in its prompt, e.g. " +
  '"The cat from [a1] sitting on the sofa from [v2]."\n' +
  "When the user asks to change, edit, continue, or reuse an existing image, the generate_image prompt " +
  "MUST contain that image's label, otherwise the image is not used at all. " +
  'If the user says "this image", "it", "the previous one" (この画像, それ, さっきの, 今の) without a label, ' +
  "they mean the most recent image.\n" +
  'Also, "this/that + thing" (このりんご, その猫, あの女の子, この服) means the thing shown in the most recent ' +
  "image that contains it, so that image's label must be in the prompt. Examples:\n" +
  '- User: このりんごを半分に切って -> prompt: "The apple from [v1], cut cleanly in half, ..."\n' +
  '- User: この子を海辺に立たせて -> prompt: "The girl from [a1], standing on a beach at sunset, ..."';

/**
 * Dynamic hint naming the most recent image(s), so "this image" / "these two" can be resolved to
 * labels. When several images arrived together (attached in one message, or generated in one
 * call), all of them are listed.
 */
function latestImageHint(latest: string[]): string {
  if (latest.length === 0) return "\nThere are no images in this conversation yet.";
  if (latest.length === 1) return `\nThe most recent image in this conversation is [${latest[0]}].`;
  const list = latest.map(l => `[${l}]`).join(", ");
  return (
    `\nThe most recent images in this conversation are ${list} (they arrived together, in this order). ` +
    `"These images" / この${latest.length}枚 means all of them; "this image" alone usually means [${latest[latest.length - 1]}].`
  );
}

/**
 * Convert internal chat history to the format expected by OpenAI.
 *
 * - Images attached by the user are sent as real image parts labeled [a1], [a2], ...
 * - Images generated by the generate_image tool are inserted right after its result as a user
 *   message labeled [v1], [v2], ... so the model can actually see what was generated.
 * Labels are assigned in order and never renumbered, so a label always means the same image.
 */
async function toOpenAIMessages(
  ctl: GeneratorController,
  history: Chat,
  media: MediaState,
): Promise<ChatCompletionMessageParam[]> {
  const messages: ChatCompletionMessageParam[] = [];
  const attachments: Record<string, string> = {};
  let turnAttachments: string[] = [];
  let attachmentCount = 0;
  let latest: string[] = [];

  // Tool calls that have not received a result yet. If the user pressed Stop while a tool was
  // running, the result may be missing from the history; an unanswered tool call breaks the next
  // request, so a "cancelled" result is filled in for it.
  let pendingToolCalls: string[] = [];
  const flushPendingToolCalls = () => {
    for (const id of pendingToolCalls) {
      messages.push({
        role: "tool",
        tool_call_id: id,
        content: "Cancelled: the user stopped this tool call before it finished.",
      } as ChatCompletionToolMessageParam);
    }
    pendingToolCalls = [];
  };

  for (const message of history) {
    if (message.getRole() !== "tool") flushPendingToolCalls();
    switch (message.getRole()) {
      case "system":
        messages.push({ role: "system", content: message.getText() });
        break;

      case "user": {
        const images = message.getFiles(ctl.client).filter(f => f.isImage());
        turnAttachments = [];
        if (images.length === 0) {
          messages.push({ role: "user", content: message.getText() });
          break;
        }
        const parts: Array<any> = [];
        latest = [];
        for (const image of images) {
          attachmentCount += 1;
          const label = `a${attachmentCount}`;
          try {
            const path = await image.getFilePath();
            attachments[label] = path;
            latest.push(label);
            turnAttachments.push(label);
            parts.push(...(await labeledImageParts(label, path, "")));
          } catch (e) {
            console.error(`Failed to read attachment ${image.name}:`, e);
            parts.push({ type: "text", text: `[${label}] (attached image could not be read)` });
          }
        }
        const text = message.getText();
        if (text) parts.push({ type: "text", text });
        messages.push({ role: "user", content: parts });
        break;
      }

      case "assistant": {
        const toolCalls: ChatCompletionMessageToolCall[] = message
          .getToolCallRequests()
          .map(toolCall => ({
            id: toolCall.id ?? "",
            type: "function",
            function: {
              name: toolCall.name,
              arguments: JSON.stringify(toolCall.arguments ?? {}),
            },
          }));

        messages.push({
          role: "assistant",
          content: message.getText(),
          ...(toolCalls.length ? { tool_calls: toolCalls } : {}),
        });
        pendingToolCalls = toolCalls.map(t => t.id);
        break;
      }

      case "tool": {
        const generated: string[] = [];
        message.getToolCallResults().forEach(toolCallResult => {
          const content = String(toolCallResult.content ?? "");
          pendingToolCalls = pendingToolCalls.filter(id => id !== (toolCallResult.toolCallId ?? ""));
          generated.push(...parseResultMarker(content));
          messages.push({
            role: "tool",
            tool_call_id: toolCallResult.toolCallId ?? "",
            content,
          } as ChatCompletionToolMessageParam);
        });

        // Show the generated images to the model ("vision promotion").
        const parts: Array<any> = [];
        if (generated.some(l => media.variants[l])) latest = [];
        for (const label of generated) {
          const path = media.variants[label];
          if (path) {
            latest.push(label);
            parts.push(...(await labeledImageParts(label, path, " (generated image)")));
          }
        }
        if (parts.length) {
          parts.push({
            type: "text",
            text:
              "These are the images you just generated. Look at them carefully and describe what you " +
              "actually see, then check them against the request. Reply in the user's language.",
          });
          messages.push({ role: "user", content: parts });
        }
        break;
      }
    }
  }

  flushPendingToolCalls();

  // Share the attachment table with the generate_image tool (same per-chat working directory).
  media.attachments = attachments;
  media.turnAttachments = turnAttachments;

  // Tell the model it can see the images itself. Merge into the existing system prompt, because
  // some chat templates (e.g. Qwen) only accept a single system message at the very beginning.
  const note = IMAGE_NOTE + latestImageHint(latest);
  const first = messages[0];
  if (first && first.role === "system" && typeof first.content === "string") {
    first.content = `${first.content}\n\n${note}`;
  } else {
    messages.unshift({ role: "system", content: note });
  }

  return messages;
}

/** Images generated by the tool call that this turn is continuing from (if any). */
function justGenerated(history: Chat): string[] {
  const all = [...history];
  const last = all[all.length - 1];
  if (!last || last.getRole() !== "tool") return [];
  return last.getToolCallResults().flatMap(r => parseResultMarker(String(r.content ?? "")));
}

/** Convert LM Studio tool definitions to OpenAI function-tool descriptors. */
function toOpenAITools(ctl: GeneratorController): ChatCompletionTool[] | undefined {
  const tools = ctl.getToolDefinitions().map<ChatCompletionTool>(t => ({
    type: "function",
    function: {
      name: t.function.name,
      description: t.function.description,
      parameters: t.function.parameters ?? {},
    },
  }));
  return tools.length ? tools : undefined;
}

